// The one security and caching policy for every ejmlabs site on Cloudflare (Workers static assets or Pages `_headers`).
// Ported from design-kit/web/_headers. Plain JavaScript so the CLI and the Vite plugin run it without a TypeScript loader.

/** Cloudflare Web Analytics: the only third party. */
export const ANALYTICS_SCRIPT = 'https://static.cloudflareinsights.com';
export const ANALYTICS_CONNECT = 'https://cloudflareinsights.com';

/** CSP directives as arrays of sources. Scripts are `'self'` plus the analytics beacon: there is no inline script, because
 *  theme-boot.js is an external file. Styles allow `'unsafe-inline'` for style attributes only (components set CSS variables
 *  such as the entrance stagger index), never for style elements. */
export function directives({ analytics = true, extra = {} } = {}) {
  const base = {
    'default-src': ["'self'"],
    'script-src': ["'self'", ...(analytics ? [ANALYTICS_SCRIPT] : [])],
    'style-src': ["'self'"],
    'style-src-attr': ["'unsafe-inline'"],
    'img-src': ["'self'", 'data:'],
    'font-src': ["'self'"],
    'connect-src': ["'self'", ...(analytics ? [ANALYTICS_CONNECT] : [])],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'none'"],
    'frame-ancestors': ["'none'"],
    'upgrade-insecure-requests': [],
  };
  for (const [name, sources] of Object.entries(extra)) base[name] = [...(base[name] ?? []), ...sources];
  return base;
}

export const csp = options => Object.entries(directives(options)).map(([n, s]) => [n, ...s].join(' ')).join('; ');

/** The contents of `_headers`. */
export function headersFile(options = {}) {
  return `# Response headers for an ejmlabs site on Cloudflare. Generated by ejm-site-headers: do not edit, change the options and run it again.
# Cloudflare joins a header that several rules set with a comma, so each header is set by one rule.
# Cache-Control: Cloudflare already sends "public, max-age=0, must-revalidate" for pages and unhashed files (theme-boot.js, the manifest),
# so only Vite's hashed files under /assets, which never change, get a rule.
/*
  Content-Security-Policy: ${csp(options)}
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
}
